#!/usr/bin/env python3
"""C# のコメントの塊を抜き出し、判定 (keep / delete / rewrite) を書き戻し、コメント以外が変わっていないことを確かめる。

    comments.py extract <パス>... [--out <JSONL>]
    comments.py apply <判定の JSONL>
    comments.py verify [<基準 ref>]

判定の基準と手順は docs/comment-cleanup.md にある。標準ライブラリだけで動く。
"""

import argparse
import bisect
import difflib
import hashlib
import json
import os
import re
import subprocess
import sys

# ツールが読むコメント。消すと生成物の扱いや解析の抑止が変わるので、抽出に出さず塊も切る。
TOOL_COMMENT = re.compile(
    r"^(?://\s*(?:<auto-generated|</auto-generated>|ReSharper\s|@formatter:|language=|noinspection\b)"
    r"|/\*\s*<auto-generated)",
    re.IGNORECASE,
)

# 本文が「ディレクティブ名の後ろ全部」なので `//` をコメントとして読まないディレクティブ。#pragma は掃除の対象外。
NO_COMMENT_DIRECTIVES = {"region", "endregion", "error", "warning", "pragma", "line"}

DOC_TAG = re.compile(
    r"</?(?:summary|remarks|param|typeparam|returns|exception|see|seealso|c|code|para|inheritdoc|value|"
    r"example|list|item|term|description|paramref|typeparamref|include)\b",
    re.IGNORECASE,
)

ID_PATTERN = re.compile(r"^(?P<file>.+):(?P<line>\d+):(?P<col>\d+)#(?P<hash>[0-9a-f]{8})$")

TOKEN = re.compile(r"\w+|[^\w\s]")

SKIPPED_DIRS = {".git", "bin", "obj"}


class UsageError(Exception):
    pass


class Scan:
    """コメントと文字列・文字のリテラルの位置 (開始, 終了) を、文字列の中の `//` を拾わずに集める。"""

    def __init__(self, text):
        self.text = text
        self.n = len(text)
        self.comments = []
        self.literals = []
        self._run()

    def _run(self):
        t, n = self.text, self.n
        i = 0
        line_start = True
        while i < n:
            c = t[i]
            if c == "\n":
                line_start = True
                i += 1
                continue
            if c in " \t\r\f\v﻿":
                i += 1
                continue
            if line_start and c == "#":
                i = self._directive(i)
                continue
            line_start = False
            if c == "/" and i + 1 < n and t[i + 1] == "/":
                end = self._line_end(i)
                self.comments.append((i, end))
                i = end
                continue
            if c == "/" and i + 1 < n and t[i + 1] == "*":
                end = self._block_end(i)
                self.comments.append((i, end))
                i = end
                continue
            end = self._literal(i) if c in "'\"$@" else None
            if end is not None:
                self.literals.append((i, end))
                i = end
                continue
            i += 1

    def _line_end(self, i):
        j = self.text.find("\n", i)
        if j < 0:
            j = self.n
        if j > i and self.text[j - 1] == "\r":
            j -= 1
        return j

    def _block_end(self, i):
        j = self.text.find("*/", i + 2)
        return self.n if j < 0 else j + 2

    def _directive(self, i):
        end = self._line_end(i)
        m = re.match(r"#\s*([A-Za-z]+)", self.text[i:end])
        name = m.group(1) if m else ""
        if name not in NO_COMMENT_DIRECTIVES:
            k = self.text.find("//", i, end)
            if k >= 0:
                self.comments.append((k, end))
        return end

    def _literal(self, i):
        t, n = self.text, self.n
        if t[i] == "'":
            return self._char_end(i)
        j = i
        dollars = 0
        verbatim = False
        while j < n and t[j] in "$@":
            if t[j] == "$":
                dollars += 1
            else:
                verbatim = True
            j += 1
        if j >= n or t[j] != '"':
            return None
        if verbatim:
            return self._verbatim_end(j + 1, dollars > 0)
        quotes = 0
        while j + quotes < n and t[j + quotes] == '"':
            quotes += 1
        if quotes >= 3:
            return self._raw_end(j + quotes, quotes, dollars)
        return self._regular_end(j + 1, dollars > 0)

    def _char_end(self, i):
        t, n = self.text, self.n
        k = i + 1
        k += 2 if k < n and t[k] == "\\" else 1
        limit = min(n, k + 10)
        while k < limit and t[k] not in "'\n":
            k += 1
        if k < n and t[k] == "'":
            return k + 1
        return i + 1

    def _regular_end(self, k, interpolated):
        t, n = self.text, self.n
        while k < n:
            c = t[k]
            if c == "\\":
                k += 2
                continue
            if c == '"':
                return k + 1
            if c == "\n":
                return k
            if interpolated and c == "{":
                if k + 1 < n and t[k + 1] == "{":
                    k += 2
                    continue
                k = self._hole_end(k + 1, 1)
                continue
            k += 1
        return n

    def _verbatim_end(self, k, interpolated):
        t, n = self.text, self.n
        while k < n:
            c = t[k]
            if c == '"':
                if k + 1 < n and t[k + 1] == '"':
                    k += 2
                    continue
                return k + 1
            if interpolated and c == "{":
                if k + 1 < n and t[k + 1] == "{":
                    k += 2
                    continue
                k = self._hole_end(k + 1, 1)
                continue
            k += 1
        return n

    def _raw_end(self, k, quotes, dollars):
        t, n = self.text, self.n
        while k < n:
            c = t[k]
            if c == '"' or (dollars and c == "{"):
                run = 1
                while k + run < n and t[k + run] == c:
                    run += 1
                if c == '"' and run >= quotes:
                    return k + run
                if c == "{" and run >= dollars:
                    k = self._hole_end(k + run, dollars)
                    continue
                k += run
                continue
            k += 1
        return n

    def _hole_end(self, k, closers):
        t, n = self.text, self.n
        depth = 0
        while k < n:
            c = t[k]
            if c == "/" and k + 1 < n and t[k + 1] == "/":
                k = self._line_end(k)
                continue
            if c == "/" and k + 1 < n and t[k + 1] == "*":
                k = self._block_end(k)
                continue
            end = self._literal(k) if c in "'\"$@" else None
            if end is not None:
                k = end
                continue
            if c in "([{":
                depth += 1
            elif c in ")]":
                depth = max(0, depth - 1)
            elif c == "}":
                if depth == 0:
                    return min(n, k + closers)
                depth -= 1
            elif c == ":" and depth == 0:
                if k + 1 < n and t[k + 1] == ":":
                    k += 2
                    continue
                close = t.find("}", k)
                return n if close < 0 else min(n, close + closers)
            k += 1
        return n


class Comment:
    def __init__(self, start, end, sl, sc, el, ec, text):
        self.start = start
        self.end = end
        self.sl = sl
        self.sc = sc
        self.el = el
        self.ec = ec
        self.text = text
        self.tool = bool(TOOL_COMMENT.match(text))


class Entry:
    def __init__(self, kind, sl, sc, el, ec, raw, text, code):
        self.kind = kind
        self.sl = sl
        self.sc = sc
        self.el = el
        self.ec = ec
        self.hash = hashlib.sha1(raw.encode("utf-8")).hexdigest()[:8]
        self.text = text
        self.code = code


class Source:
    def __init__(self, text):
        self.bom = text.startswith("﻿")
        if self.bom:
            text = text[1:]
        self.text = text
        self.scan = Scan(text)
        self.line_starts = [0] + [i + 1 for i, c in enumerate(text) if c == "\n"]
        self.lines, self.eols = split_lines(text)
        self.comments = [self._comment(s, e) for s, e in self.scan.comments]
        self.masked = self._masked_lines()
        self.has_code = self._has_code()
        self.starts_inside = self._starts_inside()
        self.entries = self._entries()

    def pos(self, offset):
        line = bisect.bisect_right(self.line_starts, offset) - 1
        return line, offset - self.line_starts[line]

    def _comment(self, start, end):
        sl, sc = self.pos(start)
        el, last = self.pos(end - 1)
        return Comment(start, end, sl, sc, el, last + 1, self.text[start:end].replace("\r", ""))

    def _masked_lines(self):
        chars = list(self.text)
        for c in self.comments:
            for i in range(c.start, c.end):
                if chars[i] not in "\r\n":
                    chars[i] = " "
        lines, _ = split_lines("".join(chars))
        return lines

    def _has_code(self):
        has_code = [line.strip() != "" for line in self.masked]
        for c in self.comments:
            if c.tool:
                for line in range(c.sl, c.el + 1):
                    has_code[line] = True
        # 複数行の /* */ は、どれかの行にコードがあれば全行を行ごと消せない。それがさらに別のコメントの行に及ぶので、変わらなくなるまで広げる。
        changed = True
        while changed:
            changed = False
            for c in self.comments:
                span = range(c.sl, c.el + 1)
                if any(has_code[line] for line in span) and not all(has_code[line] for line in span):
                    for line in span:
                        has_code[line] = True
                    changed = True
        return has_code

    def _starts_inside(self):
        spans = sorted(self.scan.literals + [(c.start, c.end) for c in self.comments])
        inside = []
        for ls in self.line_starts[: len(self.lines)]:
            k = bisect.bisect_right(spans, (ls, float("inf"))) - 1
            inside.append(k >= 0 and spans[k][0] < ls < spans[k][1])
        return inside

    def _entries(self):
        entries = []
        group = []

        def flush():
            if group:
                entries.append(self._block_entry(group))
                group.clear()

        for c in self.comments:
            if c.tool:
                flush()
                continue
            standalone = not any(self.has_code[line] for line in range(c.sl, c.el + 1))
            if not standalone:
                flush()
                entries.append(self._inline_entry(c))
                continue
            if group and c.sl > group[-1].el + 1:
                flush()
            group.append(c)
        flush()
        return entries

    def _block_entry(self, group):
        sl, el = group[0].sl, group[-1].el
        raw = self.lines[sl : el + 1]
        text = "\n".join(line.strip() for line in raw)
        return Entry("block", sl, group[0].sc, el, group[-1].ec, "\n".join(raw), text, None)

    def _inline_entry(self, c):
        code = re.sub(r"\s+", " ", " ".join(self.masked[c.sl : c.el + 1])).strip()
        return Entry("inline", c.sl, c.sc, c.el, c.ec, c.text, c.text, code)

    def next_lines(self, entry, limit=3):
        found = []
        for line in range(entry.el + 1, len(self.lines)):
            if self.masked[line].strip() == "":
                continue
            found.append(self.lines[line].strip())
            if len(found) == limit:
                break
        return found


def split_lines(text):
    pieces = text.split("\n")
    if pieces and pieces[-1] == "" and len(pieces) > 1:
        pieces.pop()
        trailing_eol = True
    else:
        trailing_eol = False
    lines, eols = [], []
    for i, piece in enumerate(pieces):
        last = i == len(pieces) - 1
        has_eol = not last or trailing_eol
        if has_eol and piece.endswith("\r"):
            lines.append(piece[:-1])
            eols.append("\r\n")
        else:
            lines.append(piece)
            eols.append("\n" if has_eol else "")
    return lines, eols


def read_text(path):
    with open(path, "rb") as f:
        data = f.read()
    return data.decode("utf-8")


def display_path(path, root):
    rel = os.path.relpath(os.path.abspath(path), os.path.abspath(root))
    if rel.startswith(".."):
        rel = os.path.abspath(path)
    return rel.replace(os.sep, "/")


def entry_record(source, entry, path):
    record = {
        "id": "%s:%d:%d#%s" % (path, entry.sl + 1, entry.sc + 1, entry.hash),
        "file": path,
        "start": entry.sl + 1,
        "end": entry.el + 1,
        "kind": entry.kind,
        "text": entry.text,
    }
    if entry.code is not None:
        record["code"] = entry.code
    record["next"] = source.next_lines(entry)
    return record


def extract_file(path, root="."):
    source = Source(read_text(path))
    shown = display_path(path, root)
    return [entry_record(source, entry, shown) for entry in source.entries]


def cs_files(paths):
    for path in paths:
        if os.path.isfile(path):
            if not path.endswith(".cs"):
                raise UsageError("%s: not a .cs file" % path)
            yield path
        elif os.path.isdir(path):
            for dirpath, dirnames, filenames in os.walk(path):
                dirnames[:] = sorted(d for d in dirnames if d not in SKIPPED_DIRS)
                for name in sorted(filenames):
                    if name.endswith(".cs"):
                        yield os.path.join(dirpath, name)
        else:
            raise UsageError("%s: no such file or directory" % path)


def extract(paths, out, root="."):
    for path in cs_files(paths):
        try:
            records = extract_file(path, root)
        except UnicodeDecodeError as e:
            raise UsageError("%s: not UTF-8 (%s)" % (path, e))
        for record in records:
            out.write(json.dumps(record, ensure_ascii=False) + "\n")


class Line:
    # 等価比較を持たせないのは、同じ中身の行どうしを list.index で取り違えないため。
    def __init__(self, text, eol):
        self.text = text
        self.eol = eol


class ApplyError(Exception):
    pass


def rewrite_lines(value):
    if not isinstance(value, str) or not value.strip():
        raise ApplyError("rewrite needs the new text in \"rewrite\" (use delete to remove the comment)")
    lines = [line.rstrip() for line in value.replace("\r\n", "\n").split("\n")]
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    for line in lines:
        if line.lstrip().startswith("/"):
            raise ApplyError("write the rewrite text without comment markers (//, ///, /*)")
    if DOC_TAG.search(value):
        raise ApplyError("rewrite must not use XML doc tags or <see cref>; write identifiers as they are")
    return ["// " + line if line else "//" for line in lines]


def leading_space(text):
    return text[: len(text) - len(text.lstrip(" \t"))]


def is_word(ch):
    return ch.isalnum() or ch == "_"


def join_around(left, right):
    if right.strip() == "":
        return left.rstrip()
    if left.strip() == "":
        return left + right.lstrip(" \t")
    if right[0] in " \t" and (left[-1] in " \t([{"):
        return left + right.lstrip(" \t")
    if is_word(left[-1]) and is_word(right[0]):
        return left + " " + right
    return left + right


def is_blank(line):
    return line.text.strip() == ""


def tidy_blank(lines, p):
    a = p
    while a > 0 and is_blank(lines[a - 1]):
        a -= 1
    b = p
    while b < len(lines) and is_blank(lines[b]):
        b += 1
    if b == a:
        return
    prev = lines[a - 1] if a > 0 else None
    nxt = lines[b] if b < len(lines) else None
    if prev is None or nxt is None or prev.text.rstrip().endswith("{") or nxt.text.lstrip().startswith("}"):
        keep = 0
    else:
        keep = 1
    if b - a > keep:
        del lines[a + keep : b]


class FileEdit:
    def __init__(self, path):
        self.path = path
        text = read_text(path)
        self.source = Source(text)
        self.objs = [Line(t, e) for t, e in zip(self.source.lines, self.source.eols)]
        self.lines = list(self.objs)
        crlf = sum(1 for e in self.source.eols if e == "\r\n")
        lf = sum(1 for e in self.source.eols if e == "\n")
        self.eol = "\r\n" if crlf > lf else "\n"
        self.by_start = {(e.sl, e.sc): e for e in self.source.entries}

    def find(self, line, col, digest):
        entry = self.by_start.get((line - 1, col - 1))
        if entry is None or entry.hash != digest:
            raise ApplyError("the comment differs from the extracted one; extract the file again")
        return entry

    def delete(self, entry):
        first = self.lines.index(self.objs[entry.sl])
        last = self.lines.index(self.objs[entry.el])
        if entry.kind == "block":
            del self.lines[first : last + 1]
            tidy_blank(self.lines, first)
            return
        head, tail = self.lines[first], self.lines[last]
        head.text = join_around(head.text[: entry.sc], tail.text[entry.ec :])
        head.eol = tail.eol
        del self.lines[first + 1 : last + 1]

    def rewrite(self, entry, body):
        if entry.kind == "block":
            first = self.lines.index(self.objs[entry.sl])
            last = self.lines.index(self.objs[entry.el])
            indent = leading_space(self.lines[first].text)
            tail_eol = self.lines[last].eol
            new = [Line(indent + text, self.eol) for text in body]
            new[-1].eol = tail_eol
            self.lines[first : last + 1] = new
            return
        self.delete(entry)
        # 複数行の文字列やコメントの途中の行の上に置くと、その中身に入ってしまうので、コードで始まる行まで上がる。
        target = entry.sl
        while target > 0 and self.source.starts_inside[target]:
            target -= 1
        at = self.lines.index(self.objs[target])
        indent = leading_space(self.lines[at].text)
        self.lines[at:at] = [Line(indent + text, self.eol) for text in body]

    def save(self):
        text = "".join(line.text + line.eol for line in self.lines)
        if text == self.source.text:
            return
        with open(self.path, "w", encoding="utf-8", newline="") as f:
            f.write(("﻿" if self.source.bom else "") + text)


def apply(judgment_lines, label, root="."):
    """判定を反映し、(数, エラーの行) を返す。エラーのある件は飛ばし、他は書き戻す。"""
    errors = []
    counts = {"keep": 0, "delete": 0, "rewrite": 0}
    by_file = {}
    seen = set()
    for number, raw in enumerate(judgment_lines, 1):
        if not raw.strip():
            continue
        where = "%s:%d" % (label, number)
        try:
            item = json.loads(raw)
        except json.JSONDecodeError as e:
            errors.append("%s: invalid JSON (%s)" % (where, e))
            continue
        if not isinstance(item, dict):
            errors.append("%s: each line must be a JSON object" % where)
            continue
        ident = item.get("id")
        m = ID_PATTERN.match(ident) if isinstance(ident, str) else None
        if m is None:
            errors.append("%s: missing or malformed \"id\" (copy it from extract)" % where)
            continue
        where = "%s: %s" % (where, ident)
        action = item.get("action")
        if action not in counts:
            errors.append("%s: \"action\" must be keep, delete or rewrite" % where)
            continue
        if ident in seen:
            errors.append("%s: duplicate id" % where)
            continue
        body = None
        if action == "rewrite":
            try:
                body = rewrite_lines(item.get("rewrite"))
            except ApplyError as e:
                errors.append("%s: %s" % (where, e))
                continue
        seen.add(ident)
        by_file.setdefault(m.group("file"), []).append(
            (where, int(m.group("line")), int(m.group("col")), m.group("hash"), action, body)
        )

    for file, items in by_file.items():
        path = os.path.join(root, file)
        if not file.endswith(".cs") or not os.path.isfile(path):
            errors.extend("%s: no such .cs file" % item[0] for item in items)
            continue
        try:
            edit = FileEdit(path)
        except UnicodeDecodeError as e:
            errors.extend("%s: not UTF-8 (%s)" % (item[0], e) for item in items)
            continue
        plan = []
        for where, line, col, digest, action, body in items:
            try:
                entry = edit.find(line, col, digest)
            except ApplyError as e:
                errors.append("%s: %s" % (where, e))
                continue
            if action == "keep":
                counts["keep"] += 1
            else:
                plan.append((entry, action, body))
        # 後ろの件から書き換えるのは、同じ行の左のコメントの列位置をずらさないため。
        plan.sort(key=lambda p: (p[0].sl, p[0].sc), reverse=True)
        for entry, action, body in plan:
            if action == "delete":
                edit.delete(entry)
            else:
                edit.rewrite(entry, body)
            counts[action] += 1
        edit.save()
    return counts, errors


def git(args, cwd, check=True):
    proc = subprocess.run(["git"] + args, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if check and proc.returncode != 0:
        raise UsageError("git %s: %s" % (" ".join(args), proc.stderr.decode("utf-8", "replace").strip()))
    return proc


def code_tokens(text):
    """コメントと空白を除いたトークンと、その行番号 (1 始まり)。文字列・文字のリテラルは中の空白ごと 1 トークンにする。"""
    if text.startswith("﻿"):
        text = text[1:]
    scan = Scan(text)
    line_starts = [0] + [i + 1 for i, c in enumerate(text) if c == "\n"]

    def line_of(offset):
        return bisect.bisect_right(line_starts, offset)

    spans = sorted([(s, e, False) for s, e in scan.comments] + [(s, e, True) for s, e in scan.literals])
    tokens = []
    pos = 0
    for start, end, literal in spans:
        for m in TOKEN.finditer(text, pos, start):
            tokens.append((m.group(), line_of(m.start())))
        if literal:
            tokens.append((text[start:end].replace("\r\n", "\n"), line_of(start)))
        pos = end
    for m in TOKEN.finditer(text, pos):
        tokens.append((m.group(), line_of(m.start())))
    return tokens


def compare(path, old_text, new_text, label):
    old = code_tokens(old_text)
    new = code_tokens(new_text)
    a = [t for t, _ in old]
    b = [t for t, _ in new]
    if a == b:
        return []
    old_lines, new_lines = set(), set()
    matcher = difflib.SequenceMatcher(None, a, b, autojunk=False)
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag != "equal":
            old_lines.update(line for _, line in old[i1:i2])
            new_lines.update(line for _, line in new[j1:j2])
    old_src = old_text.lstrip("﻿").split("\n")
    new_src = new_text.lstrip("﻿").split("\n")
    out = ["%s:%d (%s): - %s" % (path, n, label, old_src[n - 1].strip()) for n in sorted(old_lines)]
    out += ["%s:%d: + %s" % (path, n, new_src[n - 1].strip()) for n in sorted(new_lines)]
    return out


def resolve_base(ref, root):
    candidates = [ref] + (["origin/main"] if ref == "main" else [])
    for candidate in candidates:
        if git(["rev-parse", "--verify", "-q", candidate + "^{commit}"], root, check=False).returncode == 0:
            base = git(["merge-base", candidate, "HEAD"], root, check=False)
            if base.returncode == 0:
                return candidate, base.stdout.decode().strip()
            return candidate, candidate
    raise UsageError("unknown ref: %s" % ref)


def verify(ref, root="."):
    """基準 ref (HEAD との分岐点) から作業ツリーまでの .cs の変更のうち、コメントと空白以外のものを行で返す。"""
    top = git(["rev-parse", "--show-toplevel"], root).stdout.decode().strip()
    label, base = resolve_base(ref, top)
    changed = git(["diff", "--name-only", "--no-renames", "-z", base, "--", "*.cs"], top).stdout
    untracked = git(["ls-files", "--others", "--exclude-standard", "-z", "--", "*.cs"], top).stdout
    paths = sorted({p for p in (changed + untracked).decode("utf-8").split("\0") if p})
    problems = []
    for path in paths:
        shown = git(["show", "%s:%s" % (base, path)], top, check=False)
        old_text = shown.stdout.decode("utf-8", "replace") if shown.returncode == 0 else ""
        full = os.path.join(top, path)
        new_text = ""
        if os.path.isfile(full):
            with open(full, "rb") as f:
                new_text = f.read().decode("utf-8", "replace")
        problems.extend(compare(path, old_text, new_text, label))
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(prog="comments.py", description="C# comment cleanup helper (docs/comment-cleanup.md)")
    sub = parser.add_subparsers(dest="command", required=True)
    p_extract = sub.add_parser("extract", help="print each comment block of the .cs files as one JSON line")
    p_extract.add_argument("paths", nargs="+", help=".cs files or directories")
    p_extract.add_argument("--out", help="write the JSONL here instead of stdout")
    p_apply = sub.add_parser("apply", help="apply keep / delete / rewrite judgments")
    p_apply.add_argument("judgments", help="JSONL with id, action and rewrite")
    p_verify = sub.add_parser("verify", help="fail if a .cs change since the ref touches more than comments and blank lines")
    p_verify.add_argument("ref", nargs="?", default="main")
    args = parser.parse_args(argv)

    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")

    try:
        if args.command == "extract":
            if args.out:
                os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
                with open(args.out, "w", encoding="utf-8", newline="\n") as out:
                    extract(args.paths, out)
            else:
                extract(args.paths, sys.stdout)
            return 0
        if args.command == "apply":
            if not os.path.isfile(args.judgments):
                raise UsageError("%s: no such file" % args.judgments)
            with open(args.judgments, encoding="utf-8") as f:
                counts, errors = apply(f, args.judgments)
            for error in errors:
                print(error, file=sys.stderr)
            print(
                "deleted %d, rewritten %d, kept %d, errors %d"
                % (counts["delete"], counts["rewrite"], counts["keep"], len(errors))
            )
            return 1 if errors else 0
        problems = verify(args.ref)
        for problem in problems:
            print(problem)
        if problems:
            print("non-comment changes found (lines above)", file=sys.stderr)
            return 1
        return 0
    except UsageError as e:
        print("comments.py: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
