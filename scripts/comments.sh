#!/usr/bin/env bash
# shellcheck source=scripts/_lib.sh
. "$(dirname "$0")/_lib.sh"
# 塊の id に入れるハッシュを、日本語を含む本文でも awk の実装やロケールによらず同じ値にするため、バイト単位で数える。
export LC_ALL=C

usage() {
	echo "usage: comments.sh extract <path>... | apply <decisions> | verify [<base-ref>]" >&2
	exit 2
}

# 文字列の中の // をコメントと取り違えないよう、文字列と文字リテラルを読み飛ばす。
# C# 9 なので生文字列 (""") は無く、複数行にまたがるのは逐語文字列 (@"") とブロックコメントだけ。
LEXER='
BEGIN {
	for (o = 1; o < 256; o++) ord[sprintf("%c", o)] = o
	bom = sprintf("%c%c%c", 239, 187, 191)
}
function hash(s,    h, k, len) {
	h = 0
	len = length(s)
	for (k = 1; k <= len; k++) h = (h * 31 + ord[substr(s, k, 1)]) % 2147483629
	return sprintf("%08x", h)
}
function scan(s,    k, len, c, d, seg, j) {
	ccol = 0
	code = ""
	len = length(s)
	if (!inbc && !invs && !index(s, "/") && !index(s, "\"") && !index(s, q)) { code = s; return }
	k = 1
	seg = 1
	while (k <= len) {
		c = substr(s, k, 1)
		if (inbc) {
			if (c == "*" && substr(s, k + 1, 1) == "/") { inbc = 0; k += 2; seg = k; continue }
			k++
			continue
		}
		if (invs) {
			if (c == "\"") {
				if (substr(s, k + 1, 1) == "\"") { k += 2; continue }
				invs = 0
			}
			k++
			continue
		}
		d = substr(s, k, 2)
		if (d == "//") { ccol = k; break }
		if (d == "/*") { code = code substr(s, seg, k - seg); inbc = 1; k += 2; continue }
		if (d == "@\"") { invs = 1; k += 2; continue }
		if ((d == "$@" || d == "@$") && substr(s, k + 2, 1) == "\"") { invs = 1; k += 3; continue }
		if (c == "\"") {
			k++
			while (k <= len) {
				c = substr(s, k, 1)
				if (c == "\\") { k += 2; continue }
				k++
				if (c == "\"") break
			}
			continue
		}
		if (c == q) {
			if (substr(s, k + 1, 1) == "\\") {
				j = index(substr(s, k + 3), q)
				k = j ? k + 3 + j : len + 1
			} else k += 3
			continue
		}
		k++
	}
	if (!inbc) code = code substr(s, seg, (ccol ? ccol : len + 1) - seg)
}
function tool(text) {
	return text ~ /^[ \t]*\/\/[ \t]*(<auto-generated|ReSharper|@formatter|language=)/
}
function classify(s,    startbc) {
	startbc = inbc
	if (!inbc && !invs && s ~ /^[ \t]*#/) { CODE[n] = s; return "x" }
	if (!inbc && !invs && s ~ /^[ \t]*$/) return "b"
	scan(s)
	CODE[n] = code
	CCOL[n] = ccol
	if (code ~ /^[ \t]*$/) {
		if (ccol && tool(substr(s, ccol))) return "x"
		if (ccol || startbc || s ~ /^[ \t]*\/\*/) return "c"
		return "b"
	}
	if (ccol && !tool(substr(s, ccol))) return "i"
	return "x"
}
function indent(s) {
	match(s, /^[ \t]*/)
	return substr(s, 1, RLENGTH)
}
function flush(    i, e, j, k, text, id, shown) {
	if (n == 0) return
	for (i = 1; i <= n; i++) {
		if (mode == "strip") {
			if (K[i] == "x" || K[i] == "i") {
				text = CODE[i]
				sub(/^[ \t]+/, "", text)
				sub(/[ \t]+$/, "", text)
				if (text != "") print file "\t" text
			}
			continue
		}
		if (K[i] == "c") {
			for (e = i; e < n && K[e + 1] == "c"; e++) ;
			text = L[i]
			for (j = i + 1; j <= e; j++) text = text "\n" L[j]
			id = file ":" i "-" e ":" hash(text)
			if (mode == "records") print id "\tblock\t" i "\t" e "\t0\t" indent(L[i])
			else {
				print "@@ " id " block"
				print text
				print "-- next"
				shown = 0
				for (k = e + 1; k <= n && shown < 3; k++) {
					if (K[k] == "x" || K[k] == "i") { print L[k]; shown++ }
					else if (K[k] == "c") break
				}
			}
			i = e
		} else if (K[i] == "i") {
			id = file ":" i "-" i ":" hash(L[i])
			if (mode == "records") print id "\tinline\t" i "\t" i "\t" CCOL[i] "\t" indent(L[i])
			else {
				print "@@ " id " inline"
				print L[i]
			}
		}
	}
	n = 0
	inbc = 0
	invs = 0
}
FNR == 1 { flush(); file = FILENAME; sub(/^\.\//, "", file); if (index($0, bom) == 1) $0 = substr($0, 4) }
{
	n++
	L[n] = $0
	CCOL[n] = 0
	K[n] = classify($0)
}
END { flush() }
'

lex() {
	local mode="$1"
	shift
	awk -v mode="$mode" -v q="'" "$LEXER" "$@"
}

cs_files() {
	git ls-files -- "$@" | grep '\.cs$' || true
}

extract() {
	[ $# -ge 1 ] || usage
	local files
	files="$(cs_files "$@")"
	[ -n "$files" ] || { echo "extract: no tracked .cs under $*" >&2; exit 1; }
	# shellcheck disable=SC2086
	printf '%s\n' "$files" | while IFS= read -r f; do lex extract "$f"; done
}

parse_decisions() {
	awk '
		function out() { print id "\trewrite\t" text; inrw = 0 }
		inrw && /^@@end[ \t]*$/ { out(); next }
		inrw {
			line = $0
			sub(/^[ \t]*\/\/+ ?/, "", line)
			text = (first ? "" : text "\037") line
			first = 0
			next
		}
		/^[ \t]*(#.*)?$/ { next }
		$2 == "keep" || $2 == "delete" { print $1 "\t" $2 "\t"; next }
		$2 == "rewrite" { id = $1; inrw = 1; first = 1; text = ""; next }
		{ print "decisions:" FNR ": cannot read: " $0 > "/dev/stderr"; bad = 1 }
		END { if (inrw) { print "decisions: rewrite of " id " has no @@end" > "/dev/stderr"; bad = 1 } exit bad }
	' "$1"
}

APPLY='
FILENAME == ARGV[1] {
	split($0, f, "\t")
	s = f[1]
	act[s] = f[6]; kind[s] = f[2]; last[s] = f[3]; col[s] = f[4]; ind[s] = f[5]; txt[s] = f[7]
	next
}
FNR == 1 {
	bom = sprintf("%c%c%c", 239, 187, 191)
	hadbom = index($0, bom) == 1
	if (hadbom) $0 = substr($0, 4)
}
{ line[FNR] = $0; n = FNR }
function emit(x) { out[++m] = x }
function comment(prefix, text,    parts, k, j) {
	k = split(text, parts, "\037")
	for (j = 1; j <= k; j++) emit(prefix (parts[j] == "" ? "//" : "// " parts[j]))
}
END {
	m = 0
	for (i = 1; i <= n; i++) {
		if (i in act) {
			if (kind[i] == "block") {
				if (act[i] == "rewrite") comment(ind[i], txt[i])
				else deleted = 1
				i = last[i]
				continue
			}
			code = substr(line[i], 1, col[i] - 1)
			sub(/[ \t]+$/, "", code)
			if (act[i] == "rewrite") comment(ind[i], txt[i])
			emit(code)
			continue
		}
		l = line[i]
		if (deleted) {
			deleted = 0
			if (l ~ /^[ \t]*$/ && (m == 0 || out[m] ~ /^[ \t]*$/ || out[m] ~ /\{[ \t]*$/)) continue
			if (l ~ /^[ \t]*\}/ && m > 0 && out[m] ~ /^[ \t]*$/) m--
		}
		emit(l)
	}
	while (m > 0 && out[m] ~ /^[ \t]*$/) m--
	for (j = 1; j <= m; j++) print (j == 1 && hadbom ? bom : "") out[j]
}
'

apply() {
	[ $# -eq 1 ] && [ -f "$1" ] || usage
	tmp="$(mktemp -d)"
	trap 'rm -rf "$tmp"' EXIT
	parse_decisions "$1" >"$tmp/decisions"
	cut -f1 "$tmp/decisions" | sed -E 's/:[0-9]+-[0-9]+:[0-9a-f]+$//' | sort -u >"$tmp/files"
	local f errors=0 deleted=0 rewritten=0 kept=0
	while IFS= read -r f; do
		[ -n "$f" ] || continue
		if [ ! -f "$f" ]; then
			echo "$f: no such file" >&2
			errors=$((errors + $(grep -c "^$f:" "$tmp/decisions")))
			continue
		fi
		lex records "$f" >"$tmp/records"
		# 抽出の後で中身が変わった塊は位置かハッシュが合わなくなるので、id がそのまま見つかるものだけを直す。
		awk -F '\t' -v file="$f" -v err="$tmp/err" -v sum="$tmp/sum" '
			FILENAME == ARGV[1] { rec[$1] = $3 "\t" $2 "\t" $4 "\t" $5 "\t" $6; next }
			{ id = $1; sub(/:[0-9]+-[0-9]+:[0-9a-f]+$/, "", id) }
			id != file { next }
			!($1 in rec) { print $1 ": differs from the extracted one; extract again" > err; next }
			{ count[$2]++ }
			$2 != "keep" { print rec[$1] "\t" $2 "\t" $3 }
			END { print count["delete"] + 0, count["rewrite"] + 0, count["keep"] + 0 > sum }
		' "$tmp/records" "$tmp/decisions" >"$tmp/edits"
		if [ -s "$tmp/err" ]; then
			cat "$tmp/err" >&2
			errors=$((errors + $(wc -l <"$tmp/err")))
			: >"$tmp/err"
		fi
		read -r d r k <"$tmp/sum"
		deleted=$((deleted + d)) rewritten=$((rewritten + r)) kept=$((kept + k))
		if [ -s "$tmp/edits" ]; then
			awk "$APPLY" "$tmp/edits" "$f" >"$tmp/out"
			cat "$tmp/out" >"$f"
		fi
	done <"$tmp/files"
	echo "deleted $deleted, rewritten $rewritten, kept $kept, errors $errors"
	[ "$errors" -eq 0 ]
}

verify() {
	[ $# -le 1 ] || usage
	local base="${1:-main}" mb files others
	git rev-parse -q --verify "$base^{commit}" >/dev/null || base="origin/$base"
	# main が先に進んでいても、この枝で変えた分だけを見るため。
	mb="$(git merge-base HEAD "$base")"
	others="$(git diff --name-status --no-renames --diff-filter=ADT "$mb" -- '*.cs')"
	files="$(git diff --name-only --no-renames --diff-filter=M "$mb" -- '*.cs')"
	tmp="$(mktemp -d)"
	trap 'rm -rf "$tmp"' EXIT
	: >"$tmp/old"
	: >"$tmp/new"
	if [ -n "$files" ]; then
		mkdir "$tmp/base"
		# 1 ファイルずつ git show すると数千ファイルで数分かかるので、基準の版をまとめて取り出して 1 回の awk で読む。
		# shellcheck disable=SC2086
		git archive "$mb" -- $files | tar -x -C "$tmp/base"
		# shellcheck disable=SC2086
		(cd "$tmp/base" && lex strip $files) >"$tmp/old"
		# shellcheck disable=SC2086
		lex strip $files >"$tmp/new"
	fi
	{
		[ -z "$others" ] || printf '%s\n' "$others" | awk -F '\t' '{ print $2 ": " $1 " (only comments may change)" }'
		# <see cref> を消すと、それだけのために置いた using が IDE0005 で落ちるので、using を消すことだけは許す。
		{ diff "$tmp/old" "$tmp/new" || true; } | awk -F '\t' '
			/^< / && $2 ~ /^using [A-Za-z0-9_.]+;$/ { next }
			/^[<>] / { print substr($1, 3) ": " (substr($1, 1, 1) == "<" ? "- " : "+ ") substr($0, length($1) + 2) }
		'
	} >"$tmp/problems"
	[ ! -s "$tmp/problems" ] || { cat "$tmp/problems"; return 1; }
}

cmd="${1:-}"
[ $# -ge 1 ] && shift
case "$cmd" in
extract) extract "$@" ;;
apply) apply "$@" ;;
verify) verify "$@" ;;
*) usage ;;
esac
